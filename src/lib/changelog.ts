/**
 * История изменений — то, что видно в «Ещё → История изменений» и в уведомлении о новой
 * версии. Новая версия — новая запись в начале списка: уведомление сравнивает её номер
 * с тем, что пользователь уже видел.
 */

export type ChangeKind = 'new' | 'changed' | 'fixed'

export interface Change {
  kind: ChangeKind
  title: string
  text: string
  /** где это в приложении */
  where?: string
}

export interface Release {
  version: string
  /** YYYY-MM-DD */
  date: string
  title: string
  changes: Change[]
}

