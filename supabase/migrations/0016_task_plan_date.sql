-- План дня: задача, выбранная на конкретный день, хранит его дату. «Сегодня» показывает задачи
-- с plan_date = сегодня (плюс те, по которым идёт или шёл учёт), а не всё, что попадает по сроку.
-- Прошлые даты ничего не ломают: задача просто выпадает из дня, а вчерашние невыполненные
-- предлагаются при следующем выборе.
alter table tasks add column plan_date date;

create index tasks_user_plan_date_idx on tasks(user_id, plan_date) where plan_date is not null;
