// Embeds the Cyrillic-capable Roboto TTF as a base64 module for jsPDF, which ships no
// Cyrillic glyphs in its built-in fonts. Re-run after replacing the font file.
const fs = require('fs')
const path = require('path')

const fontPath = path.join(__dirname, '..', 'src', 'assets', 'fonts', 'Roboto-Regular.ttf')
const outPath = path.join(__dirname, '..', 'src', 'lib', 'pdfFont.generated.ts')

const base64 = fs.readFileSync(fontPath).toString('base64')

fs.writeFileSync(
  outPath,
  `// Generated by scripts/gen-pdf-font.cjs — do not edit by hand. Re-run after replacing the font file.\nexport const ROBOTO_REGULAR_BASE64 = '${base64}'\n`,
)

console.log(`Wrote ${outPath} (${(base64.length / 1024).toFixed(0)} KB base64)`)
